from __future__ import annotations

import json
import logging
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Optional

from config.settings import get_settings
from database.repository import Repository

logger = logging.getLogger(__name__)


class AnalyticsAgent:
    """Tracks and analyzes video performance over time."""

    def __init__(self) -> None:
        self.settings = get_settings()
        self.db = Repository()

    def record_upload(self, video_id: int, platform: str, data: dict) -> int:
        record = {
            "video_id": video_id,
            "platform": platform,
            "upload_date": datetime.now().isoformat(),
            "title": data.get("title", ""),
            "topic": data.get("topic", ""),
            "category": data.get("category", ""),
            "script": data.get("script", ""),
            "duration_seconds": data.get("duration_seconds", 0),
            "views": data.get("views", 0),
            "likes": data.get("likes", 0),
            "comments": data.get("comments", 0),
            "shares": data.get("shares", 0),
            "engagement_rate": self._calc_engagement_rate(data),
            "retention_data": data.get("retention_data", {}),
        }
        return self.db.insert_analytics(record)

    def _calc_engagement_rate(self, data: dict) -> float:
        views = data.get("views", 0) or 0
        if views == 0:
            return 0.0
        interactions = (
            (data.get("likes", 0) or 0)
            + (data.get("comments", 0) or 0)
            + (data.get("shares", 0) or 0)
        )
        return round((interactions / views) * 100, 2)

    def generate_weekly_report(self) -> Path:
        since = datetime.now() - timedelta(days=7)
        analytics = self.db.get_analytics_for_period(since)

        report_dir = self.settings.reports_dir
        report_dir.mkdir(parents=True, exist_ok=True)
        report_path = report_dir / f"weekly_analytics_{datetime.now().strftime('%Y-%m-%d')}.md"

        if not analytics:
            content = f"# Weekly Analytics Report\n**{since.date()} – {datetime.now().date()}**\n\nNo data available.\n"
            report_path.write_text(content, encoding="utf-8")
            return report_path

        lines = [
            f"# Weekly Analytics Report",
            f"**Period:** {since.date()} – {datetime.now().date()}",
            f"**Total Records:** {len(analytics)}",
            "",
            "---",
            "",
            "## Aggregate Stats",
            "",
        ]
        total_views = sum(a.get("views", 0) or 0 for a in analytics)
        total_likes = sum(a.get("likes", 0) or 0 for a in analytics)
        avg_eng = sum(a.get("engagement_rate", 0) or 0 for a in analytics) / max(len(analytics), 1)
        lines += [
            f"- **Total Views:** {total_views}",
            f"- **Total Likes:** {total_likes}",
            f"- **Avg Engagement Rate:** {avg_eng:.2f}%",
            "",
            "## Per-Video Breakdown",
            "",
            "| Title | Platform | Views | Likes | Engagement |",
            "|-------|----------|-------|-------|------------|",
        ]
        for a in sorted(analytics, key=lambda x: x.get("engagement_rate", 0), reverse=True):
            lines.append(
                f"| {a.get('title', 'N/A')[:40]} | {a.get('platform', 'N/A')} "
                f"| {a.get('views', 0)} | {a.get('likes', 0)} "
                f"| {a.get('engagement_rate', 0):.1f}% |"
            )

        lines += ["", "## Category Breakdown", "", "| Category | Videos | Avg Views | Avg Engagement |", "|----------|--------|-----------|----------------|"]
        cat_stats: dict[str, dict] = {}
        for a in analytics:
            cat = a.get("category") or a.get("vid_category", "unknown")
            if cat not in cat_stats:
                cat_stats[cat] = {"count": 0, "views": 0, "eng": 0.0}
            cat_stats[cat]["count"] += 1
            cat_stats[cat]["views"] += a.get("views", 0) or 0
            cat_stats[cat]["eng"] += a.get("engagement_rate", 0) or 0
        for cat, s in sorted(cat_stats.items(), key=lambda x: x[1]["eng"] / max(x[1]["count"], 1), reverse=True):
            lines.append(f"| {cat} | {s['count']} | {s['views'] // max(s['count'], 1)} | {s['eng'] / max(s['count'], 1):.1f}% |")

        lines += ["", "---", "*Auto-generated by AnalyticsAgent*", ""]
        content = "\n".join(lines) + "\n"
        report_path.write_text(content, encoding="utf-8")
        logger.info("Weekly analytics report: %s", report_path)
        return report_path
